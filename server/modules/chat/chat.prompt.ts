/** 从文本中识别房屋面积关键词，返回 '大' / '小' / null
 *  大面积：>120 平米 / 客户主动说"别墅/复式/大平层/大面积"
 *  小面积：≤120 平米 / 客户主动说"小户型/普通住宅/小面积"
 *  都没提到 → null（不假设） */
export function detectAreaFromText(text: string): '大' | '小' | null {
  if (!text) return null;
  if (/别墅|复式|大平层|大面积|大户型/.test(text)) return '大';
  if (/小户型|普通住宅|小面积/.test(text)) return '小';
  const m = text.match(/(\d{2,4})\s*(?:平|平米|平方米|m²|平方)/i);
  if (m) {
    const n = Number(m[1]);
    if (!Number.isNaN(n)) return n > 120 ? '大' : '小';
  }
  return null;
}

/** 把对话历史中客户消息的 content 拼成一段文本，给 detectAreaFromText 用 */
export function extractAreaFromHistory(
  historyMessages: Array<{ role: string; content: string }>,
): '大' | '小' | null {
  const customerText = historyMessages
    .filter((m) => m.role === 'customer' || m.role === 'user')
    .map((m) => m.content)
    .join('\n');
  return detectAreaFromText(customerText);
}
